// Знайди невідоме число.
//
// Календарний план 3 класу, тема 26 — «Знаходження невідомих
// компонентів дій першого ступеня: доданка, зменшуваного, від'ємника»
// і тема 28 — «...другого ступеня: множника, діленого, дільника».
// Поруч стоїть тема 27 про рівняння, і це той самий навик, лише
// записаний іншими значками.
//
// ЧОМУ ЦЕ ВАЖКО ДІТЯМ. Не через арифметику. 7 + □ = 12 дитина рахує
// легко, а □ − 4 = 9 — уже ні, бо тут треба не відняти, а додати.
// Місце невідомого міняє дію, і саме це місце ми й перебираємо:
// невідоме буває і першим числом, і другим.
//
// ЧОМУ □, А НЕ x. У третьому класі змінної ще немає (вирази зі змінною —
// це тема 21, і там інша ідея). Порожня клітинка — те, як це написано в
// підручнику.
//
// ВСЕ В МЕЖАХ 100 І БЕЗ ВІД'ЄМНИХ. Третій клас віднімає тільки більше
// від меншого; від'ємні числа з'являться в шостому.
// ═══════════════════════════════════════════════════════════════

export const meta = {
  id: 'missing-part',
  title: 'Знайди невідоме',
  rounds: 10
};

export function task(rnd){
  // Чотири родини завдань. Перші дві — перший ступінь (додавання і
  // віднімання), другі дві — другий (множення й ділення), як у плані.
  const kind = rnd(4);

  // ── доданок: 7 + □ = 12  або  □ + 7 = 12
  if(kind === 0){
    const a = 2 + rnd(48);
    const b = 2 + rnd(48);
    const sum = a + b;
    return rnd(2)
      ? { question: `${a} + □ = ${sum}`, answer: String(b), options: null }
      : { question: `□ + ${b} = ${sum}`, answer: String(a), options: null };
  }

  // ── зменшуване й від'ємник: □ − 4 = 9  або  15 − □ = 9
  // Різниця й від'ємник задаються першими, зменшуване рахується — так
  // гарантовано не вилізе від'ємний результат.
  if(kind === 1){
    const sub = 2 + rnd(48);
    const diff = 2 + rnd(48);
    const whole = sub + diff;
    return rnd(2)
      ? { question: `□ − ${sub} = ${diff}`, answer: String(whole), options: null }
      : { question: `${whole} − □ = ${diff}`, answer: String(sub), options: null };
  }

  // ── множник: 6 × □ = 42
  if(kind === 2){
    const a = 2 + rnd(8);
    const b = 2 + rnd(8);
    const p = a * b;
    return rnd(2)
      ? { question: `${a} × □ = ${p}`, answer: String(b), options: null }
      : { question: `□ × ${b} = ${p}`, answer: String(a), options: null };
  }

  // ── ділене й дільник: □ : 6 = 7  або  42 : □ = 7
  const d = 2 + rnd(8);
  const q = 2 + rnd(8);
  const whole = d * q;
  return rnd(2)
    ? { question: `□ : ${d} = ${q}`, answer: String(whole), options: null }
    : { question: `${whole} : □ = ${q}`, answer: String(d), options: null };
}
