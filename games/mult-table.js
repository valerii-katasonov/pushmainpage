// Таблиця множення і ділення в межах 100.
//
// Календарний план 3 класу, теми 8–14: повторення таблиць 2–5,
// підготовка до 6–9, самі таблиці 6–9, ділення, таблиці ділення на 6–9,
// взаємозв'язок множення й ділення.
//
// ЧОМУ МНОЖЕННЯ Й ДІЛЕННЯ РАЗОМ, А НЕ ДВІ ГРИ. Саме взаємозв'язок і є
// темою (№12 і №14 у плані). Дитина, яка вивчила 7 × 8 = 56, часто
// зупиняється на 56 : 8 — бо тренувала лише один бік. Тому в одній
// сесії трапляється і те, і те.
//
// ЧОГО ТУТ НЕМАЄ. Множників 1 і 10 — вони не тренування, а подарунок, і
// займають місце потрібніших випадків. Нуля теж: 0 × 7 діти плутають не
// через таблицю, а через саме правило, і це окрема розмова.
// ═══════════════════════════════════════════════════════════════

export const meta = {
  id: 'mult-table',
  title: 'Таблиця множення',
  rounds: 12
};

export function task(rnd){
  // 2..9 — робочий діапазон таблиці.
  const a = 2 + rnd(8);
  const b = 2 + rnd(8);
  const product = a * b;

  // Ділення трапляється приблизно в третині випадків. Рівна половина
  // виглядала б штучно: множення все ж основа, ділення — перевірка того,
  // що основа справді засвоєна.
  if(rnd(3) === 0){
    return { question: `${product} : ${a}`, answer: String(b), options: null };
  }
  return { question: `${a} × ${b}`, answer: String(product), options: null };
}
