// НАВІЩО ОКРЕМИЙ ФАЙЛ. Адреса була переписана в шести функціях окремо:
// у кожної свій ALLOWED_HOSTS, у двох ще й свій рядок із посиланням на
// портал. Поки домен один, це непомітно. Але школа купила власний
// (push.school), і виявилося, що змінити треба у восьми місцях, з яких
// одне — у листі про перший вхід. Забути хоч одне означає: людина
// отримує лист із посиланням на старий домен, або функція відмовляє
// запиту з нового зі словами «запит із невідомого джерела».
//
// Тепер адреса тут. Нову функцію писати так:
//   const { ALLOWED_HOSTS, SITE_URL, CABINET_URL } = require('./lib/site');
//
// ── ЧОМУ СТАРИЙ ДОМЕН ЛИШАЄТЬСЯ В СПИСКУ ───────────────────────
//
// На planlekcjipush.netlify.app стоїть 301 на новий домен, але цього
// замало. Портал уже доданий на початковий екран телефонів як PWA — а
// така іконка тримає СТАРУ адресу, доки людина не перевстановить її.
// Заборонити старий домен зараз означає зламати вхід усім, хто
// користується саме іконкою, і зрозуміти причину вони не зможуть.
//
// Прибирати старий рядок можна буде тоді, коли в журналі Netlify
// перестануть з'являтися запити з нього — орієнтовно за півроку, тим
// самим рухом, що й sw.js із sw-cabinet.js.
const HOST_PRIMARY = 'push.school';
const HOST_LEGACY  = 'planlekcjipush.netlify.app';

// Порядок має значення: перший — той, на який ведуть посилання в
// сповіщеннях і листах.
const ALLOWED_HOSTS = [HOST_PRIMARY, 'www.' + HOST_PRIMARY, HOST_LEGACY, 'localhost', '127.0.0.1'];

const SITE_URL    = `https://${HOST_PRIMARY}`;
// Без .html: Netlify віддає cabinet.html і за адресою /cabinet, а саме
// її людина бачить у листі й у рядку браузера.
const CABINET_URL = `${SITE_URL}/cabinet`;

// Чи дозволене джерело запиту. Порівнюємо hostname, а не шукаємо рядок
// у заголовку: «push.school» міститься і в «push.school.evil.com».
function originAllowed(origin){
  let host = '';
  try{ host = new URL(String(origin || '')).hostname; }catch(e){ return false; }
  return !!host && ALLOWED_HOSTS.includes(host);
}

module.exports = { ALLOWED_HOSTS, SITE_URL, CABINET_URL, HOST_PRIMARY, HOST_LEGACY, originAllowed };
