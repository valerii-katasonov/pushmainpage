function cors(origin) {
  return {
    'Access-Control-Allow-Origin': origin || '*',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Access-Control-Allow-Methods': 'POST, OPTIONS',
    'Content-Type': 'application/json; charset=utf-8'
  };
}
const fail = (code, msg, origin) => ({
  statusCode: code, headers: cors(origin), body: JSON.stringify({ error: msg })
});

exports.handler = async (event) => {
  const origin = event.headers.origin || event.headers.Origin || '';

  if (event.httpMethod === 'OPTIONS') return { statusCode: 204, headers: cors(origin) };
  if (event.httpMethod !== 'POST') return fail(405, 'Метод не підтримується', origin);

  // ORIGIN ОБОВ'ЯЗКОВИЙ, А НЕ «ЯКЩО Є».
  //
  // Раніше перевірка стояла під `if (origin)`, тобто запит БЕЗ цього
  // заголовка проходив без питань. Браузер шле Origin завжди, а от curl,
  // бот чи будь-який скрипт — ні. Виходило, що адресу функції достатньо
  // знати, щоб безкоштовно витрачати квоту школи на Gemini (а на платному
  // тарифі — і гроші). Саме такий доступ найлегше знайти перебором:
  // адреси netlify-функцій передбачувані.
  //
  // Тепер відсутність Origin — теж відмова. Це не броня (заголовок можна
  // підробити), але прибирає найпростіший спосіб зловживання. Надійне
  // рішення — перевірка idToken, як у child-access.js.
  {
    let host = '';
    try { host = new URL(origin || '').hostname; } catch (e) { /* ignore */ }
    if (!host || !ALLOWED_HOSTS.includes(host))
      return fail(403, 'Запит із невідомого джерела', origin);
  }

  const key = process.env.GEMINI_API_KEY;
  if (!key) return fail(500, 'AI не налаштовано: адміністратору потрібно додати GEMINI_API_KEY у Netlify', origin);

  let body;
  try { body = JSON.parse(event.body || '{}'); }
  catch (e) { return fail(400, 'Некоректний запит', origin); }

  const build = PROMPTS[body.task];
  if (!build) return fail(400, 'Невідомий тип запиту', origin);

  // Обрізаємо вхідні дані — і від помилок, і від спроб «розкрутити» модель
  const params = {
    subject: clean(body.subject, 100),
    topic: clean(body.topic, 300),
    homework: clean(body.homework, 600),
    note: clean(body.note, 600),
    textbook: clean(body.textbook, 150),
    pages: clean(body.pages, 60),
    // Текст вправи, який учитель вставив вручну — даємо більше місця
    material: clean(body.material, 2500),
    classNum: parseInt(body.classNum, 10) || 0
  };

  const spec = build(params);
  if (!spec.valid) return fail(400, spec.error, origin);

  const callGemini = (cfg) => fetch(`${API}?key=${encodeURIComponent(key)}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ contents: [{ parts: [{ text: spec.text }] }], generationConfig: cfg })
  });

  try {
    // Спроба 1: з вимкненими роздумами — інакше внутрішні токени моделі
    // з'їдають ліміт виводу і відповідь обривається на півслові.
    let r = await callGemini({ temperature: 0.7, maxOutputTokens: 2048, thinkingConfig: { thinkingBudget: 0 } });
    let data = await r.json();

    // Спроба 2: не всі моделі приймають thinkingConfig, і Google відповідає
    // загальним «invalid argument». Тому на будь-яку 400 повторюємо без
    // нього, компенсуючи збільшеним лімітом виводу.
    if (!r.ok && r.status === 400) {
      r = await callGemini({ temperature: 0.7, maxOutputTokens: 4096 });
      data = await r.json();
    }

    if (!r.ok) {
      const msg = data?.error?.message || 'Помилка сервісу Gemini';
      // 429 БУВАЄ ДВОХ ЗОВСІМ РІЗНИХ ВИДІВ, і плутати їх не можна.
      //
      // Google віддає той самий код і на денну квоту, і на хвилинну
      // (близько десяти запитів за хвилину). Ми ж завжди казали «на
      // сьогодні вичерпано» — і школа вирішувала, що до завтра ШІ мертвий,
      // хоча насправді досить було зачекати півхвилини. Особливо помітно
      // стало тепер, коли кнопка стоїть під кожним завданням: кілька
      // батьків натискають одночасно — і всі бачать «до завтра».
      //
      // Розрізняємо за тілом відповіді: у ньому є RetryInfo із затримкою
      // і QuotaFailure із назвою обмеження.
      if (r.status === 429) {
        const details = (data?.error?.details) || [];
        const retry = details.find(d => String(d['@type']||'').includes('RetryInfo'));
        const quota = details.find(d => String(d['@type']||'').includes('QuotaFailure'));
        const ids = (quota?.violations || [])
          .map(v => String(v.quotaId || v.quotaMetric || '')).join(' ');
        const secs = Math.ceil(parseFloat(String(retry?.retryDelay || '').replace('s','')) || 0);
        const perDay = /PerDay|per_day|Daily/i.test(ids);
        if (!perDay) {
          return fail(429, secs
            ? `Забагато запитів до AI за хвилину. Спробуйте за ${secs} с.`
            : 'Забагато запитів до AI за хвилину. Спробуйте за півхвилини.', origin);
        }
        // ДЕННИЙ ЛІМІТ — але вигляд у нього буває оманливий.
        //
        // Якщо в GEMINI_MODEL стоїть модель без безкоштовного тарифу
        // (з квітня 2026 це всі Pro), денна квота дорівнює нулю — і Google
        // повертає «вичерпано» вже на ПЕРШОМУ запиті дня. Школа при цьому
        // впевнена, що хтось «накрутив», і шукає винних серед батьків.
        //
        // Тому в повідомленні називаємо модель і саме обмеження: адмін
        // одразу бачить, чи це справді витрачена квота, чи модель не та.
        const quotaId = (quota?.violations || [])[0]?.quotaId || '';
        const limit = (quota?.violations || [])[0]?.quotaValue;
        console.error('[AI] 429 PerDay:', MODEL, JSON.stringify(details));
        return fail(429,
          `Денний ліміт запитів до AI вичерпано (модель «${MODEL}»`
          + (limit ? `, ліміт ${limit} на добу` : '')
          + `). Якщо це сталося з першого ж запиту — у Netlify задано модель `
          + `без безкоштовного тарифу; змініть GEMINI_MODEL на Flash.`
          + (quotaId ? ` [${quotaId}]` : ''), origin);
      }
      // МОДЕЛЬ ЗАКРИЛИ — ПИТАЄМО GOOGLE, ЩО ЗАЛИШИЛОСЯ.
      //
      // Google закриває моделі кілька разів на рік, і кожного разу школа
      // впирається в те саме: «змініть GEMINI_MODEL» — а на що саме?
      // Вгадувати назву по документації означає вгадувати ще й ліміти.
      // Тому просто запитуємо список у самого ключа: він знає точно.
      if (/no longer available|not found|is not supported|deprecat/i.test(msg)) {
        let names = [];
        try {
          const lr = await fetch(
            `https://generativelanguage.googleapis.com/v1beta/models?key=${encodeURIComponent(key)}`);
          const ld = await lr.json();
          names = (ld?.models || [])
            // Лише ті, що вміють відповідати текстом, і лише робочі
            // (preview і exp закриваються так само раптово).
            .filter(m => (m.supportedGenerationMethods || []).includes('generateContent'))
            .map(m => String(m.name || '').replace('models/', ''))
            .filter(n => /flash/i.test(n) && !/preview|exp|thinking|image|tts|live/i.test(n))
            // Ту, що щойно відмовила, не пропонуємо — Google перелічує її
            // серед доступних, хоча відповідати нею вже не можна.
            .filter(n => n !== MODEL)
            // Спершу псевдоніми «-latest»: вони самі стежать за поточною
            // моделлю Google, тож не зникнуть при наступному закритті.
            .sort((a, b) => (/latest$/.test(b) ? 1 : 0) - (/latest$/.test(a) ? 1 : 0));
        } catch (e) { /* список не дістали — впораємося без нього */ }
        console.error('[AI] Модель недоступна:', MODEL, '· доступні:', names.join(', '));
        return fail(r.status,
          `Модель «${MODEL}» більше не доступна.`
          + (names.length
              ? ` Адміністратору: у Netlify → GEMINI_MODEL постав одну з доступних — `
                + names.slice(0, 6).join(', ') + '.'
              : ' Адміністратору: змініть змінну GEMINI_MODEL у Netlify.'), origin);
      }
      return fail(r.status, msg, origin);
    }

    const cand = data?.candidates?.[0];
    const text = (cand?.content?.parts || []).map(p => p?.text || '').join('').trim();
    if (!text) return fail(502, 'AI не повернув відповіді. Спробуйте ще раз.', origin);

    return {
      statusCode: 200,
      headers: cors(origin),
      body: JSON.stringify({ text, truncated: cand?.finishReason === 'MAX_TOKENS' })
    };
  } catch (e) {
    return fail(500, 'Не вдалося звернутися до AI: ' + e.message, origin);
  }
};
